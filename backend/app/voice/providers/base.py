"""Base abstract interfaces for provider-agnostic Speech-to-Text and Text-to-Speech engines."""

from abc import ABC, abstractmethod
from typing import AsyncGenerator, List, Optional

from app.schemas.voice import TranscriptPayload, VisemeTiming


class BaseSTTProvider(ABC):
    """Abstract interface for Speech-to-Text streaming and batch transcription."""

    name: str = "base_stt"

    @abstractmethod
    async def connect(self, language: str = "en-US", sample_rate: int = 16000) -> None:
        """Initializes connection or session with the STT engine."""
        pass

    @abstractmethod
    async def send_audio(self, audio_bytes: bytes) -> None:
        """Feeds raw audio chunk to the STT provider."""
        pass

    @abstractmethod
    async def receive_transcript(self) -> Optional[TranscriptPayload]:
        """Polls or receives intermediate streaming transcript event if available."""
        pass

    @abstractmethod
    async def finish_stream(self) -> Optional[TranscriptPayload]:
        """Finalizes the streaming session and returns the consolidated final transcript."""
        pass

    @abstractmethod
    async def disconnect(self) -> None:
        """Tears down provider socket or HTTP sessions."""
        pass


class BaseTTSProvider(ABC):
    """Abstract interface for Text-to-Speech neural audio generation."""

    name: str = "base_tts"

    @abstractmethod
    async def synthesize(
        self,
        text: str,
        voice_id: Optional[str] = None,
        language: Optional[str] = None,
    ) -> bytes:
        """Synthesizes text into complete audio bytes (MP3/WAV/PCM)."""
        pass

    @abstractmethod
    def stream_audio(
        self,
        text: str,
        voice_id: Optional[str] = None,
        language: Optional[str] = None,
    ) -> AsyncGenerator[bytes, None]:
        """Streams audio chunks asynchronously as they are generated by the neural model."""
        pass

    @abstractmethod
    async def get_visemes(self, text: str) -> List[VisemeTiming]:
        """Calculates or extracts phonetic viseme alignments for facial animation."""
        pass

    @abstractmethod
    async def cancel(self) -> None:
        """Aborts in-flight synthesis."""
        pass
